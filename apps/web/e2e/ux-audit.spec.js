test('Escape on a dropdown or calendar in a form leaves the form and what was typed alone', async ({ page }) => {
  await register(page)
  await page.goto('/planner')
  await page.getByRole('button', { name: 'New task' }).click()
  await page.getByLabel('Title').fill('Half typed')
  await page.getByLabel('Repeat').click()
  await expect(page.getByRole('listbox')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('listbox')).toHaveCount(0)
  await expect(page.getByLabel('Title')).toHaveValue('Half typed')
  await page.getByLabel('Due date').click()
  await expect(page.getByRole('dialog', { name: 'Choose date' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Choose date' })).toHaveCount(0)
  await expect(page.getByLabel('Title')).toHaveValue('Half typed')
})

