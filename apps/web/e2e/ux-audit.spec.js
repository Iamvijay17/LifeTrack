test('new accounts get a guide, ticked off by real data, and upcoming deadlines reach the dashboard', async ({ page }) => {
  await register(page)
  const guide = page.getByTestId('getting-started')
  await expect(guide).toBeVisible()
  await page.goto('/jobs')
  await addApplication(page, 'Followup Co')
  await page.getByRole('tab', { name: 'Table' }).click()
  await page.getByRole('button', { name: 'Followup Co', exact: true }).click()
  await page.getByRole('button', { name: 'Edit' }).click()
  const editForm = page.getByRole('dialog', { name: 'Edit application' })
  const tomorrow = new Date(Date.now() + 864e5).toLocaleDateString('en-CA')
  await pickDate(editForm.getByLabel('Follow-up date'), tomorrow)
  await editForm.getByRole('button', { name: 'Save', exact: true }).click()
  await page.goto('/')
  const row = page.getByRole('link', { name: /Follow up with Followup Co.*Tomorrow/ })
  await expect(row).toBeVisible()
  await row.click()
  await expect(page.getByRole('dialog', { name: 'Followup Co' })).toBeVisible()
})

