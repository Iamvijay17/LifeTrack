import { test, expect } from '@playwright/test'
import { pickDate, register } from './helpers'

const addApplication = async (page, company) => {
  await page.getByRole('button', { name: /^Application$/ }).click()
  await page.getByLabel('Company').fill(company)
  await page.getByLabel('Job title').fill('Engineer')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}

test("a menu on the table's last row isn't cut off by the card", async ({ page }) => {
  await register(page)
  await page.goto('/jobs')
  await addApplication(page, 'First Co')
  await addApplication(page, 'Last Co')
  await page.getByRole('tab', { name: 'Table' }).click()
  await page
    .getByRole('button', { name: /^Move / })
    .last()
    .click()
  await expect(page.getByRole('menuitem').last()).toBeInViewport({ ratio: 1 })
})

